def run_wp(args: list[str]) -> tuple[int, str, str]:
    """Run WP-CLI in the sidecar that actually has the wp binary."""
    result = subprocess.run(
        ["docker", "exec", CONTAINER, *WP_BASE, *args],
        capture_output=True,
        text=True,
    )
    return result.returncode, result.stdout.strip(), result.stderr.strip()


def get_existing_count() -> int:
    code, out, _ = run_wp(["post", "list", "--post_status=publish", "--post_type=post", "--format=count"])
    return int(out) if code == 0 and out.isdigit() else 0


def find_post_id(slug: str) -> int | None:
    code, out, _ = run_wp(["post", "list", f"--name={slug}", "--post_type=post", "--post_status=any", "--format=ids"])
    if code != 0 or not out.strip():
        return None
    try:
        return int(out.split()[0])
    except ValueError:
        return None


def create_post(title: str, slug: str, content: str) -> bool:
    existing = find_post_id(slug)
    if existing is not None:
        print(f"  = [{existing}] already present: {title}")
        return True

    # Wrap content in <p> tags so the plugin sends proper HTML to the vector API
    html_content = '<p>' + '</p><p>'.join(
        s.strip() for s in content.split('. ') if s.strip()
    ) + '</p>'

    code, out, err = run_wp([
        "post", "create",
        f"--post_title={title}",
        f"--post_name={slug}",
        "--post_status=publish",
        "--post_type=post",
        f"--post_content={html_content}",
    ])
    if code == 0:
        post_id = out.split()[-1].rstrip('.')
        print(f"  ✓ [{post_id}] {title}")
        return True
    print(f"  ✗ {title}: {err[:160]}")
    return False


def main():
    print(f"Checking existing posts…")
    existing = get_existing_count()
    print(f"  Found {existing} published posts.\n")

    to_create = [a for a in ARTICLES]
    print(f"Seeding {len(to_create)} articles into WordPress…")
    print("(The plugin will automatically index each post to the vector API on save.)\n")

    ok = err = 0
    for title, slug, content in to_create:
        if create_post(title, slug, content):
            ok += 1
        else:
            err += 1

    print(f"\nDone. Created: {ok}, Errors: {err}")
    print(f"Total posts now: {existing + ok}")
    print("\nRun 'Начать сканирование' in the plugin settings to reindex all posts.")


if __name__ == "__main__":
    main()
